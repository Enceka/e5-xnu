#!/usr/bin/env python3
"""Rasterise an 8x16 ASCII font into boot/m0/font8x16.h.

The M0 stub draws text straight into the RGB565 framebuffer at 0xbe000000, so
the font has to be small enough to embed in a 21 KB blob: 95 glyphs x 16 bytes
is 1520 bytes.  Menlo at 13 pt has an advance width of exactly 8 px (10/11/12 pt
give 6/7/7), which makes a clean 8x16 cell.  Its ink sits at y=4..13, so each
glyph is drawn at y=-2 to centre it.

Usage: python3 tools/mkfont.py [path/to/font.ttc]
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Menlo.ttc"
SIZE = 13
OFFSET_Y = -2
OUT = "boot/m0/font8x16.h"
FIRST, LAST = 0x20, 0x7E


def glyph(font, ch):
    im = Image.new("1", (8, 16), 0)
    ImageDraw.Draw(im).text((0, OFFSET_Y), ch, font=font, fill=1)
    px = im.load()
    rows = []
    for y in range(16):
        bits = 0
        for x in range(8):
            if px[x, y]:
                bits |= 1 << (7 - x)
        rows.append(bits)
    return rows


def main():
    font = ImageFont.truetype(FONT, SIZE, index=0)
    out = [
        "/* Generated by tools/mkfont.py -- do not edit.",
        " * Source: " + FONT + " at %d pt, cell 8x16, ASCII 0x20..0x7E." % SIZE,
        " * Each glyph is 16 rows, one byte per row, MSB = leftmost pixel. */",
        "#ifndef M0_FONT8X16_H",
        "#define M0_FONT8X16_H",
        "",
        "#define FONT_FIRST 0x20",
        "#define FONT_LAST 0x7e",
        "",
        "static const unsigned char font8x16[(FONT_LAST - FONT_FIRST + 1) * 16] = {",
    ]
    for code in range(FIRST, LAST + 1):
        rows = glyph(font, chr(code))
        label = "space" if code == 0x20 else chr(code)
        out.append("/* 0x%02x %s */" % (code, label))
        out.append("    " + ", ".join("0x%02x" % r for r in rows) + ",")
    out += ["};", "", "#endif /* M0_FONT8X16_H */", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("wrote %s: %d glyphs, %d bytes of bitmap" % (OUT, LAST - FIRST + 1, (LAST - FIRST + 1) * 16))


if __name__ == "__main__":
    main()
